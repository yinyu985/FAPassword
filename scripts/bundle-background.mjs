import { readFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { Script } from "node:vm";
import { build } from "esbuild";
import { writeAtomic } from "./build-files.mjs";

export const backgroundPath = "src/background.bundle.js";
export const languagePath = "src/language.bundle.js";
export const compileLanguage = root => compileClassic(root, "src/language.js", languagePath);
export const compileBackground = root => compileClassic(root, "src/background.js", backgroundPath);
async function compileClassic(root, source, output) {
  const result = await build({
    absWorkingDir: root, entryPoints: [source], outfile: output,
    bundle: true, write: false, metafile: true, format: "iife", platform: "browser",
    target: ["chrome123"], charset: "utf8", legalComments: "none", logLevel: "silent",
    banner: { js: `// Generated by npm run bundle:background from ${source}. Do not edit.` },
  });
  if (result.outputFiles.length !== 1 || Object.values(result.metafile.outputs).some(output => output.imports.length)) {
    throw new Error(`${output} must be one self-contained classic script, with no runtime imports`);
  }
  new Script(result.outputFiles[0].text, { filename: output });
  return result.outputFiles[0].contents;
}
export async function checkBackground(root) {
  const manifest = JSON.parse(await readFile(join(root, "manifest.json"), "utf8"));
  if (manifest.background?.service_worker !== backgroundPath || manifest.background.type) {
    throw new Error("The root extension must use the generated classic background worker");
  }
  for (const [path, compile] of [[backgroundPath, compileBackground], [languagePath, compileLanguage]]) {
    const actual = await readFile(join(root, path)).catch(() => null);
    if (!actual?.equals(Buffer.from(await compile(root)))) throw new Error(`${path} missing or stale. Run npm run bundle:background`);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  if (process.argv.includes("--check")) await checkBackground(root);
  else {
    await writeAtomic(join(root, backgroundPath), await compileBackground(root));
    await writeAtomic(join(root, languagePath), await compileLanguage(root));
    console.log(`Updated ${backgroundPath} and ${languagePath}`);
  }
}
