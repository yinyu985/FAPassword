import { readFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { Script } from "node:vm";
import { build } from "esbuild";
import { writeAtomic } from "./build-files.mjs";

export const backgroundPath = "src/background.bundle.js";
export async function compileBackground(root) {
  const result = await build({
    absWorkingDir: root, entryPoints: ["src/background.js"], outfile: backgroundPath,
    bundle: true, write: false, metafile: true, format: "iife", platform: "browser",
    target: ["chrome123"], charset: "utf8", legalComments: "none", logLevel: "silent",
    banner: { js: "// Generated by npm run bundle:background from src/background.js. Do not edit." },
  });
  if (result.outputFiles.length !== 1 || Object.values(result.metafile.outputs).some(output => output.imports.length)) {
    throw new Error("The background must be one self-contained classic script, with no runtime imports");
  }
  new Script(result.outputFiles[0].text, { filename: backgroundPath });
  return result.outputFiles[0].contents;
}
export async function checkBackground(root) {
  const manifest = JSON.parse(await readFile(join(root, "manifest.json"), "utf8"));
  if (manifest.background?.service_worker !== backgroundPath || manifest.background.type) {
    throw new Error("The root extension must use the generated classic background worker");
  }
  const expected = await compileBackground(root);
  let actual;
  try { actual = await readFile(join(root, backgroundPath)); } catch {}
  if (!actual?.equals(Buffer.from(expected))) {
    throw new Error("Background bundle missing or stale. Run npm run bundle:background and include the generated file");
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  if (process.argv.includes("--check")) await checkBackground(root);
  else {
    await writeAtomic(join(root, backgroundPath), await compileBackground(root));
    console.log(`Background worker bundle: ${join(root, backgroundPath)}`);
  }
}
